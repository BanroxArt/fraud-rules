#!/usr/bin/env python3
"""Regenerate compiled/: SQL per dialect and Sigma YAML for the bundled pack.

The compiled files are committed so teams that only want SQL or Sigma can take
them without installing anything. tests/test_compiled.py fails when they are
out of date.

Usage: python scripts/build_compiled.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fraudrules import sigma  # noqa: E402
from fraudrules.loader import load_pack  # noqa: E402
from fraudrules.sql import DIALECTS, compile_rule, transpile  # noqa: E402

HEADER = "-- Generated by scripts/build_compiled.py from {path}. Do not edit.\n-- {id} {title}\n"


def build() -> dict[Path, str]:
    out: dict[Path, str] = {}
    rules = load_pack()
    for r in rules:
        base = f"{r.id.lower()}-{r.name}"
        sql = compile_rule(r)
        for d in DIALECTS:
            head = HEADER.format(path=f"src/fraudrules/rules/{r.category}/{r.path}", id=r.id, title=r.title)
            out[ROOT / "compiled" / "sql" / d / f"{base}.sql"] = head + transpile(sql, d) + ";\n"
    for r, text in sigma.iter_sigma(rules):
        name = f"{r.id.lower()}_{r.name.replace('-', '_')}.yml"
        out[ROOT / "compiled" / "sigma" / name] = text
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    files = build()
    existing = {p for p in (ROOT / "compiled").rglob("*") if p.is_file() and p.name != "README.md"}
    stale = sorted(str(p.relative_to(ROOT)) for p in existing - set(files))
    changed = sorted(
        str(p.relative_to(ROOT)) for p, text in files.items() if not p.is_file() or p.read_text() != text
    )
    if check:
        for p in stale + changed:
            print(f"out of date: {p}")
        return 1 if stale or changed else 0
    for p in existing - set(files):
        p.unlink()
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
